package langprofile

import "testing"

func TestGenerated(t *testing.T) {
	for _, p := range []string{"partners/activity/v1/activity-pb.gw.go", "a/b.pb.gw.go", "x/api.pb.go", "x/api_grpc.pb.go", "svc/foo_pb2.py", "web/x.d.ts",
		"k/zz_generated.deepcopy.go", "app/db/migrations/0001_init.py", "node_modules/x/y.js", "lib/user.g.dart", "gen/client.go"} {
		if !IsGeneratedPath(p) {
			t.Errorf("%s should be generated", p)
		}
	}
	for _, p := range []string{"internal/app/service.go", "svc/main.py", "web/app.ts", "docs/gen_notes.go"} {
		if IsGeneratedPath(p) {
			t.Errorf("%s is hand-written", p)
		}
	}
	if !IsGenerated("a.go", []string{"// Code generated by protoc-gen-go. DO NOT EDIT."}) || IsGenerated("a.go", []string{"package a"}) {
		t.Error("header detection")
	}
}

func TestIsTest(t *testing.T) {
	for p, want := range map[string]bool{"a/b_test.go": true, "tests/test_x.py": true, "x/test_x.py": true, "web/a.spec.ts": true, "web/a.ts": false, "a/b.go": false, "Sources/AppTests/FooTests.swift": true} {
		if IsTest(p) != want {
			t.Errorf("IsTest(%s) = %v", p, !want)
		}
	}
}

func TestUntestable(t *testing.T) {
	cases := map[string]string{
		"resp, err := http.Get(url)":                "network",
		"return squirrel.Select(\"a\").From(\"t\")": "SQL",
		"c, err := ftp.Dial(addr)":                  "FTP / SFTP",
		"data, _ := os.ReadFile(p)":                 "filesystem / OS",
		"return a + b":                              "",
		"s := fmt.Sprintf(\"%d\", n)":               "",
		"client.Publish(redis.NewClient(opts))":     "message broker / cache",
	}
	for body, want := range cases {
		if got := Untestable("a.go", body); got != want {
			t.Errorf("Untestable(%q) = %q, want %q", body, got, want)
		}
	}
}
