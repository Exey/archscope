// For returns the profile owning path's extension, or nil.
func For(p string) *Profile {
	e := strings.ToLower(path.Ext(p))
	for _, pr := range profiles {
		for _, x := range pr.Exts {
			if x == e {
				return pr
			}
		}
	}
	return nil
}

func norm(p string) string { return strings.ToLower(strings.ReplaceAll(p, "\\", "/")) }

func dirParts(p string) []string {
	parts := strings.Split(path.Dir(p), "/")
	return parts
}

// IsGeneratedName reports a generated file by its name alone (`x.pb.gw.go`,
// `zz_generated.deepcopy.go`, `a_pb2.py`), whichever directory it sits in.
func IsGeneratedName(p string) bool {
	base := path.Base(norm(p))
	for _, pr := range profiles {
		for _, s := range pr.Generated.Suffixes {
			if strings.HasSuffix(base, s) {
				return true
			}
		}
		for _, s := range pr.Generated.Prefixes {
			if strings.HasPrefix(base, s) {
				return true
			}
		}
	}
	return false
}

// IsGeneratedPath reports files that are produced, not written, by name or
// directory alone: protobuf/gRPC stubs, mocks, declaration files, minified
// bundles, ORM migrations, vendored code.
func IsGeneratedPath(p string) bool {
	if IsGeneratedName(p) {
		return true
	}
	l := norm(p)
	for _, d := range common.dirs {
		if strings.Contains(l, "/"+d+"/") || strings.HasPrefix(l, d+"/") {
			return true
		}
	}
	return false
}

// IsGeneratedHeader reports a "code generated" / "do not edit" marker in the first lines.
func IsGeneratedHeader(raw []string) bool {
	for i := 0; i < len(raw) && i < 8; i++ {
		l := strings.ToLower(raw[i])
		for _, m := range common.headerMarkers {
			if strings.Contains(l, m) {
				return true
			}
		}
	}
	return false
}

// IsGenerated is IsGeneratedPath or IsGeneratedHeader; raw may be nil when the
// file has not been read.
func IsGenerated(p string, raw []string) bool { return IsGeneratedPath(p) || IsGeneratedHeader(raw) }

// IsTest reports whether p is a test file, by its language's conventions.
func IsTest(p string) bool {
	l := norm(p)
	base := path.Base(l)
	for _, part := range dirParts(l) {
		switch part {
		case "test", "tests", "__tests__", "testdata", "spec", "specs", "e2e":
			return true
		}
	}
	if pr := For(p); pr != nil {
		for _, s := range pr.Tests.Suffixes {
			if strings.HasSuffix(base, s) {
				return true
			}
		}
		for _, s := range pr.Tests.Contains {
			if strings.Contains(base, s) {
				return true
			}
		}
		for _, s := range pr.Tests.Prefixes {
			if strings.HasPrefix(base, s) {
				return true
			}
		}
	}
	return false
}

// Untestable names the technology that puts the code in body (a function's
// text) beyond a unit test — "SQL", "network", "FTP / SFTP", … — or "".
func Untestable(p, body string) string {
	if pr := For(p); pr != nil {
		for _, t := range pr.Untestable {
			if t.Re.MatchString(body) {
				return t.Name
			}
		}
	}
	for _, t := range shared {
		if t.Re.MatchString(body) {
			return t.Name
		}
	}
	return ""
}
