// Package langprofile holds, per language, the settings the rules share: which
// files are generated (and so nobody's to fix), which are tests, how
// documentation is written, and which technologies put a function out of reach
// of a unit test. Rules ask the profile instead of each carrying its own list,
// so a language is tuned in one place.
package langprofile

import (
	"path"
	"regexp"
	"strings"
)

// DocStyle says where a language keeps documentation.
type DocStyle string

const (
	DocComment   DocStyle = "comment"   // a comment directly above the declaration
	DocDocstring DocStyle = "docstring" // a string literal first in the body
)

// Tech is a technology a function can touch that a unit test cannot stand in for
// without a real (or faked) service behind it.
type Tech struct {
	Name string
	Re   *regexp.Regexp
}

// TestRules says which files are tests.
type TestRules struct {
	Suffixes []string // file-name suffixes: "_test.go"
	Contains []string // file-name fragments: ".spec."
	Prefixes []string // file-name prefixes: "test_"
	Dirs     []string // directory names
}

// GeneratedRules says which files are machine-written.
type GeneratedRules struct {
	Suffixes []string // file-name suffixes of machine-written files
	Prefixes []string
	Dirs     []string // directory names that hold generated code
}

// Profile is one language's settings.
type Profile struct {
	ID        string
	Exts      []string
	Doc       DocStyle
	Tests     TestRules
	Generated GeneratedRules
	// Untestable are the technologies, beyond the shared ones, specific to the language.
	Untestable []Tech

	Syntax Syntax // comments, strings, documentation markers
	Values ValueSyntax
	Naming Naming
	Funcs  FuncConventions
	Limits Limits // thresholds the Code Structure card applies
}

func tech(name, re string) Tech { return Tech{name, regexp.MustCompile(re)} }

