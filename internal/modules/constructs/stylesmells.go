// stylesmells.go is the 🧹 Style & design subcard of Code Structure: rules
// ported from thai-lint (and their Go / Rust counterparts) that catch what AI
// assistants and hurried edits leave behind —
//
//   - comments and docstrings that describe a change instead of the code,
//   - linter / type-checker suppressions with no reason given,
//   - stringly-typed code (one value compared with many string literals),
//   - Python: stateless classes, getters that should be properties, look-before-
//     you-leap checks, filter-in-loop, command/query mixing, print() in
//     libraries, Manager/Helper god-class names,
//   - Go: Get-prefixed getters, look-before-you-leap, fmt.Print in libraries,
//     empty-struct namespaces,
//   - Rust: unwrap/expect, clone() in loops, blocking calls in async fns.
//
// Everything is lexical over the masked source (srcmask.go) and the Python
// docstring model (pydocs.go). Every issue is a normal CSIssue, so it is
// suppressible, shows in review mode on the lines a merge request adds, and
// reaches the Code Quality score unless it is marked Advisory.
package constructs

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"github.com/exey/archscope/internal/security"
)

// styleCtx collects one file's style issues.
type styleCtx struct {
	path, fe string
	m        maskedFile
	out      []CSIssue
}

// add records an issue at a 0-based line.
func (c *styleCtx) add(line int, sev security.Severity, id, rule, msg, detail string, advisory bool) {
	if line < 0 || line >= len(c.m.raw) {
		return
	}
	snip := strings.TrimSpace(c.m.raw[line])
	if len(snip) > 100 {
		snip = snip[:100] + "…"
	}
	c.out = append(c.out, CSIssue{RuleID: id, Rule: rule, Message: msg, Detail: detail, Severity: sev,
		FilePath: c.path, Line: line + 1, Snippet: snip, Advisory: advisory})
}

// scanStyle runs every style rule that applies to the file's language.
func scanStyle(path, fe string, m maskedFile) []CSIssue {
	if isGeneratedSource(m.raw) {
		return nil
	}
	c := &styleCtx{path: path, fe: fe, m: m}
	c.scanComments()
	c.scanStringly()
	switch fe {
	case ".py":
		c.scanPython()
	case ".go":
		c.scanGo()
	case ".rs":
		c.scanRust()
	}
	return c.out
}

// isGeneratedSource spots machine-written files by their header.
func isGeneratedSource(raw []string) bool {
	for i := 0; i < len(raw) && i < 8; i++ {
		l := strings.ToLower(raw[i])
		if strings.Contains(l, "code generated") || strings.Contains(l, "do not edit") || strings.Contains(l, "autogenerated") || strings.Contains(l, "auto-generated") {
			return true
		}
	}
	return false
}

// ── comments ─────────────────────────────────────────────────────────────────

// cmtBlock is a run of comment lines read as one paragraph.
type cmtBlock struct {
	first, last int // 0-based lines
	text        string
	whole       bool // every line is only a comment (not a trailing one)
}

// lineComment is the comment text of one line — what masking blanked out —
// with its markers (//, #, /*, *, ///) removed; "" when the line has none.
func lineComment(raw, text string) string {
	s, e := -1, -1
	for i := 0; i < len(raw) && i < len(text); i++ {
		if raw[i] != text[i] {
			if s < 0 {
				s = i
			}
			e = i
		}
	}
	if s < 0 {
		return ""
	}
	t := strings.TrimSpace(raw[s : e+1])
	t = strings.TrimSuffix(t, "*/")
	t = strings.TrimLeft(t, "/#*!< \t")
	return strings.TrimSpace(t)
}

// commentBlocks groups consecutive comment-only lines (a trailing comment on a
// code line is a block of its own).
func commentBlocks(m maskedFile) []cmtBlock {
	var out []cmtBlock
	for i := 0; i < len(m.raw); i++ {
		t := lineComment(m.raw[i], m.text[i])
		if t == "" {
			continue
		}
		only := strings.TrimSpace(m.text[i]) == ""
		b := cmtBlock{first: i, last: i, whole: only}
		parts := []string{t}
		for only && i+1 < len(m.raw) {
			n := lineComment(m.raw[i+1], m.text[i+1])
			if n == "" || strings.TrimSpace(m.text[i+1]) != "" {
				break
			}
			parts = append(parts, n)
			i++
			b.last = i
		}
		b.text = strings.Join(parts, "\n")
		out = append(out, b)
	}
	return out
}

// uw wraps a phrase so it only matches whole words in any script — Go's \b is
// ASCII-only and would never fire around Cyrillic.
func uw(p string) *regexp.Regexp {
	return regexp.MustCompile(`(?i)(?:^|[^\p{L}\p{N}_])(?:` + p + `)(?:[^\p{L}\p{N}_]|$)`)
}

type phrase struct {
	re    *regexp.Regexp
	label string
}

// Tier 1: phrases whose referent is a *change*, which a reader of the merged file
// cannot resolve. Chosen like thai-lint's: neither can describe what code does
// while running. Anywhere in a comment or docstring.
var changePhrases = []phrase{
	{uw(`used to be`), "used to be"},
	{uw(`before this (?:\w+ )?(?:change|commit|pr|mr|diff|patch|refactor|migration)`), "before this change"},
	{uw(`(?:after|since) this (?:commit|pr|mr|diff|patch|refactor)`), "since this change"},
	{uw(`this (?:pr|mr|commit) (?:adds?|added|fix(?:es|ed)|removes?|removed|replaces?|replaced|moves?|moved|renames?|renamed|introduces?|introduced)`), "this change …"},
	{uw(`до этого (?:изменения|коммита|pr|mr|мр|патча|рефакторинга|пр)`), "до этого изменения"},
	{uw(`после этого (?:изменения|коммита|pr|mr|мр|патча|рефакторинга|пр)`), "после этого изменения"},
	{uw(`в этом (?:pr|mr|мр|пр|коммите|изменении|патче) (?:добавлен\w*|убран\w*|удал[её]н\w*|исправлен\w*|заменён\w*|заменен\w*|перенесён\w*|перенесен\w*|переименован\w*)`), "в этом изменении …"},
	{uw(`раньше (?:было|здесь|тут|использовал\w*)|ранее (?:было|здесь|тут)`), "раньше было"},
	{uw(`использовал(?:ся|ась|ось|ись) (?:раньше|ранее)`), "использовалось раньше"},
}

// Tier 2: atemporal language in documentation (docstrings and doc comments) —
// "currently", "will be", dates, "replaced by". Advisory: plausible in plain comments.
var temporalPhrases = []phrase{
	{uw(`currently|for now|at the moment|recently|soon|coming soon`), "currently / now"},
	{uw(`planned|to be added|to be implemented|will be added|will be implemented|will be removed|will be replaced`), "future reference"},
	{uw(`formerly|replaced by|migrated from|old implementation|new implementation|legacy implementation`), "state change"},
	{regexp.MustCompile(`\b20\d\d-\d\d-\d\d\b|(?i)\b(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+20\d\d\b`), "date"},
	{uw(`в настоящее время|на данный момент|пока что|недавно|скоро|временно`), "сейчас / теперь"},
	{uw(`планируется|будет добавлен\w*|будет реализован\w*|в будущем`), "планы"},
	{uw(`заменяет|заменён|заменен|мигрирован\w*|старая реализация|новая реализация|ранее`), "смена состояния"},
}

var rePassiveUsedTo = regexp.MustCompile(`(?i)\b(?:is|are|was|were|be|been|being|not|also|only|can be|could be|to be)\s+used to\b`)

func firstPhrase(text string, set []phrase) string {
	for _, p := range set {
		for _, loc := range p.re.FindAllStringIndex(text, -1) {
			if quotedMention(text, loc[0], loc[1]) {
				continue // the doc talks ABOUT the phrase ("currently"), it doesn't use it
			}
			if p.label == "used to be" && rePassiveUsedTo.MatchString(text) {
				continue
			}
			return p.label
		}
	}
	return ""
}

// quotedMention: the match (which uw() extends by one delimiter on each side) is
// wrapped in matching quote marks.
func quotedMention(text string, start, end int) bool {
	if end-start < 3 {
		return false
	}
	q := text[start]
	return (q == '"' || q == '\'' || q == '`') && text[end-1] == q
}

// reDeclStart marks a line that begins a declaration — what a doc comment sits above.
var reDeclStart = regexp.MustCompile(`^\s*(?:func|type|class|interface|struct|enum|trait|impl|pub|export|public|private|protected|static|abstract|const|var|let|def|fn)\b`)

// scanComments covers the comment-driven rules: change-referential prose, and
// suppressions without a reason.
func (c *styleCtx) scanComments() {
	m := c.m
	for _, b := range commentBlocks(m) {
		if strings.HasPrefix(strings.TrimSpace(b.text), "go:") || strings.HasPrefix(b.text, "nolint") {
			continue
		}
		if ph := firstPhrase(b.text, changePhrases); ph != "" {
			c.add(b.first, security.SevLow, "comment-change-ref", "Comment describes a change, not the code",
				"Say what the code does and why; how it used to be belongs in the commit message, where it stays true.", ph, false)
			continue
		}
		next := b.last + 1
		if c.fe != ".py" && b.whole && next < len(m.code) && reDeclStart.MatchString(m.code[next]) {
			if ph := firstPhrase(b.text, temporalPhrases); ph != "" {
				c.add(b.first, security.SevLow, "doc-temporal", "Time-bound wording in a doc comment",
					"Documentation should stay true after the merge: describe what the code does, not when or relative to what it was written.", ph, true)
			}
		}
	}
	if c.fe == ".py" {
		for _, d := range pyDocs(m) {
			if !d.has {
				continue
			}
			if ph := firstPhrase(d.text, changePhrases); ph != "" {
				c.add(d.docStart, security.SevLow, "comment-change-ref", "Docstring describes a change, not the code",
					"Say what the code does and why; how it used to be belongs in the commit message, where it stays true.", ph, false)
			} else if ph := firstPhrase(d.text, temporalPhrases); ph != "" {
				c.add(d.docStart, security.SevLow, "doc-temporal", "Time-bound wording in a docstring",
					"Documentation should stay true after the merge: describe what the code does, not when or relative to what it was written.", ph, true)
			}
		}
	}
	c.scanSuppressions()
}

// ── suppressions without a reason ────────────────────────────────────────────

// suppression directives: the regexp captures the codes (1) and what follows (2).
var suppressRes = []struct {
	name string
	re   *regexp.Regexp
}{
	{"noqa", regexp.MustCompile(`(?i)\bnoqa\b(?::?\s*([A-Z]{1,5}\d{1,5}(?:\s*,\s*[A-Z]{1,5}\d{1,5})*))?(.*)$`)},
	{"type: ignore", regexp.MustCompile(`\btype:\s*ignore(?:\[([^\]]*)\])?(.*)$`)},
	{"pylint: disable", regexp.MustCompile(`\bpylint:\s*disable(?:-next|-line)?\s*=\s*([\w\-, ]+?)(?:\s{2,}|\s+#|$)(.*)$`)},
	{"pyright: ignore", regexp.MustCompile(`\bpyright:\s*ignore(?:\[([^\]]*)\])?(.*)$`)},
	{"nosec", regexp.MustCompile(`\bnosec\b\s*(G\d+|B\d+)?(.*)$`)},
	{"nolint", regexp.MustCompile(`\bnolint\b(?::\s*([\w,\-]+))?(.*)$`)},
	{"lint:ignore", regexp.MustCompile(`\blint:ignore\s+(\S+)(.*)$`)},
	{"@ts-ignore", regexp.MustCompile(`@ts-ignore\b()(.*)$`)},
	{"@ts-nocheck", regexp.MustCompile(`@ts-nocheck\b()(.*)$`)},
	{"@ts-expect-error", regexp.MustCompile(`@ts-expect-error\b()(.*)$`)},
	{"eslint-disable", regexp.MustCompile(`\beslint-disable(?:-next-line|-line)?\b\s*([\w@/\-, ]*?)(?:\s+--\s*(.*))?$`)},
}

// hasReason reports whether the text after a directive explains it: at least
// two words, or one long one, once separators and bare codes are dropped.
var reBareCode = regexp.MustCompile(`^[A-Z]{1,5}\d{1,5}$`)

func hasReason(rest string) bool {
	rest = strings.TrimLeft(strings.TrimSpace(rest), "-—–:#/;,. \t")
	words, letters := 0, 0
	for _, w := range strings.FieldsFunc(rest, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '\'' }) {
		if len(w) >= 2 && !reBareCode.MatchString(w) {
			words++
			letters += len([]rune(w))
		}
	}
	return words >= 2 || letters >= 10
}

func (c *styleCtx) scanSuppressions() {
	m := c.m
	// thai-lint's convention: a module docstring with a "Suppressions:" section
	// explains the file's suppressions in one place.
	if c.fe == ".py" {
		for _, d := range pyDocs(m) {
			if d.kind == "module" && d.has && strings.Contains(strings.ToLower(d.text), "suppressions:") {
				return
			}
		}
	}
	for i := range m.raw {
		t := lineComment(m.raw[i], m.text[i])
		if t == "" {
			continue
		}
		// a comment may chain directives and prose: "# type: ignore  # the stub is wrong"
		sep := "#"
		if c.fe != ".py" {
			sep = "//"
		}
		segs := strings.Split(t, sep)
		for k, seg := range segs {
			s, g := matchSuppression(strings.TrimSpace(seg))
			if g == nil {
				continue
			}
			codes, rest := strings.TrimSpace(g[1]), g[2]+" "+strings.Join(segs[k+1:], " ")
			if hasReason(rest) {
				break
			}
			// a plain comment line directly above counts as the justification
			if i > 0 && strings.TrimSpace(m.text[i-1]) == "" {
				if p := lineComment(m.raw[i-1], m.text[i-1]); p != "" && hasReason(p) && !suppressLike(p) {
					break
				}
			}
			if codes == "" && s != "@ts-ignore" && s != "@ts-nocheck" && s != "@ts-expect-error" {
				c.add(i, security.SevMedium, "lazy-ignore-blanket", "Blanket suppression without a reason",
					"This silences every rule on the line. Name the rule and say why it does not apply, e.g. `# noqa: E501 — long URL`.", s, false)
			} else {
				c.add(i, security.SevLow, "lazy-ignore", "Suppression without a reason",
					"Say why the rule does not apply here, after the directive or on the line above — an unexplained suppression hides a problem instead of settling it.", s, false)
			}
			break
		}
	}
}

// matchSuppression finds a directive that STARTS the comment segment (so prose
// that merely mentions "noqa" is not one).
func matchSuppression(seg string) (string, []string) {
	for _, s := range suppressRes {
		if loc := s.re.FindStringIndex(seg); loc != nil && strings.TrimSpace(seg[:loc[0]]) == "" {
			return s.name, s.re.FindStringSubmatch(seg)
		}
	}
	return "", nil
}

func suppressLike(s string) bool {
	for _, r := range suppressRes {
		if r.re.MatchString(s) {
			return true
		}
	}
	return false
}

// ── stringly-typed ───────────────────────────────────────────────────────────

var (
	reStrEq      = regexp.MustCompile(`([A-Za-z_][\w.]*(?:\[[^\]\n]{1,20}\])?)\s*(?:===|!==|==|!=)\s*(?:"([A-Za-z_][\w\-]{0,23})"|'([A-Za-z_][\w\-]{0,23})')`)
	reStrEqRev   = regexp.MustCompile(`(?:"([A-Za-z_][\w\-]{0,23})"|'([A-Za-z_][\w\-]{0,23})')\s*(?:===|!==|==|!=)\s*([A-Za-z_][\w.]*(?:\[[^\]\n]{1,20}\])?)`)
	reStrIn      = regexp.MustCompile(`([A-Za-z_][\w.]*)\s+(?:not\s+)?in\s*[\(\[\{]((?:\s*(?:"[A-Za-z_][\w\-]{0,23}"|'[A-Za-z_][\w\-]{0,23}')\s*,?)+)\s*[\)\]\}]`)
	reStrLit     = regexp.MustCompile(`"([A-Za-z_][\w\-]{0,23})"|'([A-Za-z_][\w\-]{0,23})'`)
	reSwitchOn   = regexp.MustCompile(`^\s*switch\s*(?:\(\s*)?([A-Za-z_][\w.]*(?:\[[^\]\n]{1,20}\])?)(?:\s*\))?\s*\{`)
	reCaseLits   = regexp.MustCompile(`^\s*case\s+(.+?):`)
	stringlySkip = map[string]bool{"os.name": true, "sys.platform": true, "platform": true, "__name__": true, "typeof": true, "args[0]": true, "key": true, "name": true, "ext": true}
)

// scanStringly flags one expression that is compared with three or more
// different string literals in a file — values an enum (or constants) would name.
func (c *styleCtx) scanStringly() {
	switch c.fe {
	case ".py", ".go", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts":
	default:
		return
	}
	type use struct {
		lits  map[string]bool
		sites int
		first int
	}
	uses := map[string]*use{}
	note := func(expr string, line int, lits ...string) {
		if stringlySkip[expr] || expr == "" {
			return
		}
		u := uses[expr]
		if u == nil {
			u = &use{lits: map[string]bool{}, first: line}
			uses[expr] = u
		}
		for _, l := range lits {
			if l != "" {
				u.lits[l] = true
			}
		}
		u.sites++
	}
	pick := func(a, b string) string {
		if a != "" {
			return a
		}
		return b
	}
	type sw struct {
		expr  string
		depth int
	}
	var stack []sw
	depth := 0
	for i, l := range c.m.text {
		code := c.m.code[i]
		for _, g := range reStrEq.FindAllStringSubmatch(l, -1) {
			note(g[1], i, pick(g[2], g[3]))
		}
		for _, g := range reStrEqRev.FindAllStringSubmatch(l, -1) {
			note(g[3], i, pick(g[1], g[2]))
		}
		for _, g := range reStrIn.FindAllStringSubmatch(l, -1) {
			if i0 := strings.Index(l, g[0]); i0 >= 0 && strings.Contains(l[:i0+len(g[1])], "for ") {
				continue // a for-loop's iterable, not a comparison
			}
			var lits []string
			for _, lg := range reStrLit.FindAllStringSubmatch(g[2], -1) {
				lits = append(lits, pick(lg[1], lg[2]))
			}
			note(g[1], i, lits...)
		}
		if c.fe != ".py" {
			if g := reSwitchOn.FindStringSubmatch(code); g != nil {
				stack = append(stack, sw{g[1], depth})
			}
			if len(stack) > 0 && depth == stack[len(stack)-1].depth+1 {
				if g := reCaseLits.FindStringSubmatch(l); g != nil {
					var lits []string
					for _, lg := range reStrLit.FindAllStringSubmatch(g[1], -1) {
						lits = append(lits, pick(lg[1], lg[2]))
					}
					note(stack[len(stack)-1].expr, i, lits...)
				}
			}
			depth += strings.Count(code, "{") - strings.Count(code, "}")
			for len(stack) > 0 && depth <= stack[len(stack)-1].depth {
				stack = stack[:len(stack)-1]
			}
		}
	}
	for expr, u := range uses {
		if len(u.lits) < 3 {
			continue
		}
		var vals []string
		for v := range u.lits {
			vals = append(vals, v)
		}
		sort.Strings(vals)
		shown := vals
		if len(shown) > 4 {
			shown = shown[:4]
		}
		c.add(u.first, security.SevLow, "stringly-typed", "One value compared with many string literals",
			"An enum (or named constants) makes the allowed values explicit, lets the type checker see them, and removes typo risk.",
			fmt.Sprintf("`%s` vs %s%s", expr, strings.Join(shown, ", "), map[bool]string{true: ", …"}[len(vals) > 4]), true)
	}
}
