// Package markdown renders an AnalysisResult as a structured Markdown document.
// It is assembled from the same card table as the HTML report (report.Cards):
// the repo-wide cards first, then each platform's cards — so whatever a card
// shows in the HTML it carries here too, and a card added to one format cannot
// be missing from the other (see report/cards.go). The result is plain text
// tables and headings with no CSS or JavaScript.
package markdown

import (
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/exey/archscope/internal/report"
	"github.com/exey/archscope/internal/result"
	"github.com/exey/archscope/internal/scanner"
	"github.com/exey/archscope/internal/security"
)

// Write renders res as Markdown and writes it to outPath.
func Write(res *result.AnalysisResult, outPath string) error {
	doc := Render(res)
	return os.WriteFile(outPath, []byte(doc), 0o644)
}

// Render returns the full Markdown document: the repo-wide cards, then one
// section per platform.
func Render(res *result.AnalysisResult) string {
	var b strings.Builder
	b.WriteString(header(res))
	b.WriteString(report.MarkdownGlobal(res))
	for _, pg := range res.PlatformTabs() {
		renderPlatform(&b, res, pg)
	}
	b.WriteString(footer())
	return b.String()
}

// RenderGlobal returns the repo-wide part only — the title and every Global
// card, no platform sections. It is what the HTML report's header "MD" button
// downloads.
func RenderGlobal(res *result.AnalysisResult) string {
	var b strings.Builder
	b.WriteString(header(res))
	b.WriteString(report.MarkdownGlobal(res))
	b.WriteString(footer())
	return b.String()
}

// RenderPlatform returns the Markdown for one platform section (equivalent to
// one HTML platform card) — used by the HTML report for each card's "MD" view
// and its download button.
func RenderPlatform(res *result.AnalysisResult, pg *scanner.PlatformGroup) string {
	var b strings.Builder
	renderPlatform(&b, res, pg)
	return b.String()
}

func header(res *result.AnalysisResult) string {
	src := res.RootPath
	if res.IsRemote && res.SourceURL != "" {
		src = res.SourceURL
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# ArchScope — %s\n\n> Generated %s · %s files · %s lines\n>\n> Source: `%s`",
		res.ProjectName, time.Now().Format("2006-01-02"), fmtNum(len(res.Files)), fmtNum(res.TotalLines()), src)
	if langs := strings.Join(res.Scan.ProjectTypes, ", "); langs != "" {
		fmt.Fprintf(&b, " · %s", langs)
	}
	b.WriteString("\n\n---\n\n")
	return b.String()
}

func footer() string {
	return fmt.Sprintf("_Generated by [ArchScope v%s](https://github.com/Exey/archscope/tree/main) · Exey Panteleev · %s_\n",
		report.Version, time.Now().Format("2006-01-02"))
}

// renderPlatform writes one platform section (equivalent to one HTML platform card).
func renderPlatform(b *strings.Builder, res *result.AnalysisResult, pg *scanner.PlatformGroup) {
	files := res.FilesForPlatform(pg.Platform)
	if len(files) == 0 {
		return
	}
	fmt.Fprintf(b, "## %s\n\n", pg.TabLabel())
	b.WriteString(report.MarkdownPlatform(res, pg, files))
	b.WriteString("---\n\n")
}

// ── Helpers ───────────────────────────────────────────────────────────────────

func mdCell(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}

func fmtNum(n int) string {
	s := fmt.Sprintf("%d", n)
	if n < 1000 {
		return s
	}
	var out []byte
	for i, ch := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, byte(ch))
	}
	return string(out)
}

// ── CWE Index ─────────────────────────────────────────────────────────────────

// CWEIndex is the "Security Coverage — CWE Index" table: every CWE the built-in
// rules cover, with the rule names, severity and languages. It is the Markdown
// counterpart of the Security Rules grid in the HTML Danger Index card.
func CWEIndex() string { return renderCWEIndexMD() }

func renderCWEIndexMD() string {
	type cweRow struct {
		num       int
		names     []string // deduplicated rule names
		count     int      // number of distinct rules mapped to this CWE
		severity  security.Severity
		langs     []string // display names
		universal bool     // true if any rule for this CWE is language-universal
	}
	byCWE := map[int]*cweRow{}
	langLabel := map[string]string{
		"go": "Go", "python": "Python", "swift": "Swift",
		"kotlin": "Kotlin", "ts": "TS/JS",
	}
	for _, r := range security.Default.Rules() {
		if r.CWE == "" {
			continue
		}
		n, err := strconv.Atoi(r.CWE)
		if err != nil {
			continue
		}
		row := byCWE[n]
		if row == nil {
			row = &cweRow{num: n, severity: r.Severity}
			byCWE[n] = row
		}
		row.count++
		// Deduplicate rule names.
		found := false
		for _, existing := range row.names {
			if existing == r.Name {
				found = true
				break
			}
		}
		if !found && r.Name != "" {
			row.names = append(row.names, r.Name)
		}
		// Track language coverage.
		if len(r.Languages) == 0 {
			row.universal = true
		} else {
			for _, lid := range r.Languages {
				label := langLabel[lid]
				if label == "" {
					label = lid
				}
				already := false
				for _, l := range row.langs {
					if l == label {
						already = true
						break
					}
				}
				if !already {
					row.langs = append(row.langs, label)
				}
			}
		}
		// Promote severity to highest seen.
		if r.Severity.Rank() > row.severity.Rank() {
			row.severity = r.Severity
		}
	}
	if len(byCWE) == 0 {
		return ""
	}
	rows := make([]*cweRow, 0, len(byCWE))
	for _, r := range byCWE {
		rows = append(rows, r)
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].num < rows[j].num })

	cweDesc := map[int]string{
		16:   "Security Configuration Errors",
		22:   "Path Traversal",
		78:   "OS Command Injection",
		79:   "Cross-Site Scripting",
		89:   "SQL Injection",
		94:   "Code Injection",
		117:  "Log Output Neutralization",
		119:  "Buffer Overflow",
		272:  "Least Privilege Violation",
		276:  "Incorrect Default Permissions",
		295:  "Improper Certificate Validation",
		311:  "Missing Encryption of Sensitive Data",
		319:  "Cleartext Transmission",
		321:  "Hard-coded Cryptographic Key",
		327:  "Broken or Risky Crypto Algorithm",
		328:  "Weak Hash",
		329:  "Not Using Random IV with CBC Mode",
		338:  "Cryptographically Weak PRNG",
		346:  "Origin Validation Error",
		347:  "Improper Cryptographic Signature Check",
		352:  "Cross-Site Request Forgery",
		362:  "Race Condition (TOCTOU)",
		400:  "Uncontrolled Resource Consumption",
		434:  "Unrestricted File Upload",
		476:  "NULL Pointer Dereference",
		477:  "Use of Obsolete Function",
		489:  "Active Debug Code",
		502:  "Deserialization of Untrusted Data",
		522:  "Insufficiently Protected Credentials",
		530:  "Exposure of Backup File",
		532:  "Sensitive Info in Log File",
		601:  "URL Redirection to Untrusted Site",
		611:  "XML External Entity (XXE)",
		614:  "Sensitive Cookie Without Secure Flag",
		693:  "Protection Mechanism Failure",
		732:  "Incorrect Permission Assign for Crit. Resource",
		749:  "Exposed Dangerous Method",
		770:  "Allocation of Resources Without Limits",
		798:  "Hard-coded Credentials",
		913:  "Improper Control of Dynamic-Managed Code",
		916:  "Weak Password Hash Algorithm",
		918:  "Server-Side Request Forgery",
		922:  "Insecure Storage of Sensitive Info",
		926:  "Improper Export of Android Components",
		942:  "Permissive CORS Policy",
		943:  "NoSQL Injection",
		1004: "Sensitive Cookie Without HttpOnly Flag",
		1321: "Prototype Pollution",
		1299: "Missing Protection for Alternate Hardware",
		1333: "Regular Expression DoS",
		1336: "Server-Side Template Injection",
	}

	var b strings.Builder
	b.WriteString("### 📋 Security Rules — CWE Index\n\n")
	fmt.Fprintf(&b, "%d distinct CWEs covered across all languages.\n\n", len(rows))
	b.WriteString("| CWE | Vulnerability | Checks | Severity | Languages |\n")
	b.WriteString("|-----|---------------|-------:|----------|-----------|\n")
	for _, r := range rows {
		desc := cweDesc[r.num]
		if desc == "" {
			desc = strings.Join(r.names, " / ")
		}
		if desc == "" {
			desc = "—"
		}
		langs := "all"
		if !r.universal && len(r.langs) > 0 {
			sort.Strings(r.langs)
			langs = strings.Join(r.langs, ", ")
		}
		fmt.Fprintf(&b, "| [CWE-%d](https://cwe.mitre.org/data/definitions/%d.html) | %s | %d | %s | %s |\n",
			r.num, r.num, mdCell(desc), r.count, string(r.severity), langs)
	}
	b.WriteString("\n")
	return b.String()
}
